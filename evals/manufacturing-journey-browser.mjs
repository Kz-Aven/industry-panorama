import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { readFileSync } from 'node:fs';

const {chromium}=await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const browser=await chromium.launch({channel:'chrome',headless:true});
const file=resolve('outputs/manufacturing-business-journey.html');
const html=readFileSync(file,'utf8');
const payload=JSON.parse(html.match(/<script type="application\/json" id="map-data">([^<]+)<\/script>/)[1]);
assert.equal(new Set(payload.cases.map(item=>item.file)).size,66);
assert.ok(payload.cases.every(item=>item.work.length>0));
assert.ok(payload.assetIds.length>0);
assert.ok(payload.art.factory.includes('data-object-id="receiving-'));
try {
  const context=await browser.newContext({offline:true,viewport:{width:1512,height:1000}});
  const page=await context.newPage();
  const errors=[],remote=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(/^https?:/.test(request.url())) remote.push(request.url());});
  await page.goto(pathToFileURL(file).href);
  await page.locator('.site img').evaluateAll(images=>Promise.all(images.map(img=>img.decode())));
  assert.equal(await page.locator('.site').count(),4);
  assert.equal(await page.locator('.outside-edge').count(),5);
  await page.screenshot({path:'outputs/previews/manufacturing-business-journey.png',fullPage:true});
  await page.locator('.outside-edge').first().click();
  assert.match(await page.locator('#detail').innerText(),/上游供应商 → 制造企业/);
  await page.locator('.section-title [data-view=factory]').click();
  await page.locator('.floor img').evaluate(img=>img.decode());
  assert.equal(await page.locator('.floor-pin').count(),6);
  assert.equal(await page.locator('.factory-route path[marker-end]').count(),3);
  await page.screenshot({path:'outputs/previews/manufacturing-continuous-workspaces.png',fullPage:true});
  await page.locator('[data-area=receiving]').click();
  await page.locator('#detail [data-case=case-59]').click();
  assert.match(await page.locator('#detail h3').innerText(),/来料跟催/);
  await page.locator('#flow-tabs [data-flow=trace]').click();
  assert.equal(await page.locator('.factory-route path[marker-end]').count(),3);
  assert.match(await page.locator('#tracked').innerText(),/成品批次/);
  await page.locator('#view-tabs [data-view=roles]').click();
  assert.equal(await page.locator('.lane-task').count(),4);
  await page.locator('.lane-task').nth(1).click();
  assert.match(await page.locator('#detail h3').innerText(),/查发运/);
  await page.locator('#detail [data-open-area=shipping]').click();
  assert.equal(await page.locator('[data-area=shipping]').getAttribute('aria-pressed'),'true');
  await page.locator('#detail summary').click();
  const originalCase=page.locator('#detail [data-case=case-32]');
  await originalCase.scrollIntoViewIfNeeded();
  const scroll=await page.evaluate(()=>scrollY);
  await originalCase.click();
  assert.match(await page.locator('#detail h3').innerText(),/放行前追溯码专项核对清单/);
  await page.locator('#detail [data-case-back]').click();
  assert.match(await page.locator('#detail h3').innerText(),/放行与发运/);
  assert.equal(await page.locator('#detail details').evaluate(element=>element.open),true);
  assert.equal(await originalCase.evaluate(element=>element===document.activeElement),true);
  assert.equal(await page.evaluate(()=>scrollY),scroll);
  assert.equal(new URL(page.url()).hash,'');
  assert.equal(await page.locator('[data-area=shipping]').getAttribute('aria-pressed'),'true');
  assert.equal(await page.locator('#flow-tabs [data-flow=trace]').getAttribute('aria-pressed'),'true');
  await page.locator('#view-tabs [data-view=objects]').click();
  await page.locator('[data-record="2"]').click();
  assert.match(await page.locator('#detail h3').innerText(),/原辅料批次/);
  await page.locator('header [data-view=cases]').click();
  assert.equal(await page.locator('#case-list button').count(),66);
  await page.locator('#group-filter').selectOption('production-quality');
  assert.equal(await page.locator('#case-list button').count(),10);
  await page.locator('#group-filter').selectOption('');
  await page.locator('#case-query').fill('接单评审');
  assert.equal(await page.locator('#case-list button').count(),1);
  await page.locator('#case-list button').click();
  await page.locator('#detail [data-case-back]').click();
  assert.equal(await page.locator('#case-query').inputValue(),'接单评审');
  assert.equal(await page.locator('#case-list button').count(),1);
  await page.locator('#case-query').clear();
  for(const item of payload.cases){
    await page.locator('#case-list [data-case='+item.id+']').click();
    assert.equal(await page.locator('#detail h3').innerText(),item.title);
    assert.equal(new URL(page.url()).hash,'#'+item.id);
    assert.equal(await page.locator('#detail summary').first().innerText(),'原案例的工作步骤');
  }
  await page.reload();
  assert.equal(await page.locator('#detail h3').innerText(),payload.cases.at(-1).title);
  await page.locator('#detail [data-case-back]').click();
  assert.equal(await page.locator('#case-list button').count(),66);
  assert.equal(new URL(page.url()).hash,'');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#view-tabs [data-view=journey]').click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.deepEqual(errors,[]);
  assert.deepEqual(remote,[]);
  console.log('66 案例逐一打开 · 4 条主线 · 6 工区 · 上下游与泳道切换 · 390 px 离线');
}finally{await browser.close();}
